"""Screener-style automatic Pros & Cons and Morningstar-style letter grades.

Every statement is generated by an explicit rule from stored numbers - no free text:

* Ratio vs peers: scoring points approximate the percentile among sector peers (or the
  whole universe), so >= 80 points -> "top 20 %" (pro), <= 20 -> "bottom 20 %" (con).
* Multi-year trends: revenue / net income growth or decline, debt growth or reduction.
* Red flags: every HIGH-severity flag of the latest year is a con.
* Published scores: Piotroski F 8-9 (strong) / 0-2 (weak) as in Piotroski (2000);
  Altman Z'' safe / distress zone; Beneish M above -1.78.

Letter grades follow the distribution Morningstar documented for its Financial Health
grades (top 10 % A, 20 % B, 40 % C, 20 % D, bottom 10 % F). The cut-offs are the universe
percentiles P90 / P70 / P30 / P10 of each category score, written to scoring_config.json
by ``python main.py calibrate`` (``grade_bands``).
"""

from __future__ import annotations

from collections.abc import Iterable
from dataclasses import dataclass, field
from datetime import date
from decimal import Decimal
from typing import Any

from app.analysis.health_score import curve_for, interpolate
from app.analysis.ratios import RATIO_DEFINITIONS, RatioOutcome
from app.analysis.red_flags import RedFlag
from app.analysis.trends import TrendOutcome

GRADE_LEVELS = (("A", 90), ("B", 70), ("C", 30), ("D", 10))  # universe percentiles


def grade_for(category: str, score: Decimal | float | None,
              config: dict[str, Any]) -> str | None:
    """Letter grade from calibrated cut-offs; ``None`` if not calibrated or no score."""
    bands = (config.get("grade_bands") or {}).get(category)
    if score is None or not bands:
        return None
    for band in bands:
        if float(score) >= float(band["min"]):
            return str(band["grade"])
    return "F"


@dataclass
class Insights:
    pros: list[str] = field(default_factory=list)
    cons: list[str] = field(default_factory=list)


def _fmt(value: Decimal, unit: str) -> str:
    return f"{float(value):,.1f}%" if unit == "%" else f"{float(value):,.2f}x"


def generate_insights(ratios: Iterable[RatioOutcome], trends: Iterable[TrendOutcome],
                      flags: Iterable[RedFlag], config: dict[str, Any], sector: str | None,
                      period: date | None, max_ratio_items: int = 4) -> Insights:
    result = Insights()
    if period is None:
        return result
    ratios = [r for r in ratios if r.period == period]
    by_code = {r.code: r for r in ratios}
    metric_specs = {code: spec for cat in config["categories"].values()
                    for code, spec in cat["metrics"].items()}

    ranked: list[tuple[float, str, str]] = []
    for code, spec in metric_specs.items():
        outcome = by_code.get(code)
        if outcome is None or not outcome.ok:
            continue
        curve, basis = curve_for(spec, sector)
        points = interpolate(float(outcome.value), curve)
        definition = RATIO_DEFINITIONS[code]
        peers = f"{sector} peers" if basis.startswith("vs ") and sector and sector in basis \
            else "large listed companies"
        text = f"{definition.name} of {_fmt(outcome.value, definition.unit)}"
        if points >= 80:
            ranked.append((points, "pro", f"{text} is in the top {100 - int(points)}% of {peers}"))
        elif points <= 20:
            ranked.append((100 - points, "con",
                           f"{text} is in the bottom {max(int(points), 1)}% of {peers}"))
    ranked.sort(reverse=True)
    result.pros += [t for _, kind, t in ranked if kind == "pro"][:max_ratio_items]
    result.cons += [t for _, kind, t in ranked if kind == "con"][:max_ratio_items]

    multi = {t.metric_code: t for t in trends if t.comparison_type == "MULTI_YEAR"}
    for code, label in (("total_revenue", "Revenue"), ("net_income", "Net income")):
        t = multi.get(code)
        if t is None or t.percentage_change is None or t.previous_period is None:
            continue
        years = t.current_period.year - t.previous_period.year
        cagr = float(t.percentage_change)
        if t.direction == "UP" and cagr >= 10:
            result.pros.append(f"{label} grew {cagr:.1f}% a year over {years} years")
        elif t.direction == "DOWN":
            result.cons.append(f"{label} fell over {years} years (CAGR {cagr:.1f}%)")
    debt = multi.get("total_debt")
    if debt is not None and debt.percentage_change is not None:
        cagr = float(debt.percentage_change)
        if debt.direction == "DOWN":
            result.pros.append(f"Debt reduced over the period (CAGR {cagr:.1f}%)")
        elif cagr >= 15:
            result.cons.append(f"Debt grew {cagr:.1f}% a year")

    for flag in flags:
        if flag.period == period and flag.severity == "HIGH":
            result.cons.append(f"Red flag: {flag.title} ({flag.triggered_condition})")

    f_score = by_code.get("piotroski_f_score")
    if f_score is not None and f_score.ok:
        if f_score.value >= 8:
            result.pros.append(f"Piotroski F-Score {int(f_score.value)}/9 (strong group, "
                               "Piotroski 2000)")
        elif f_score.value <= 2:
            result.cons.append(f"Piotroski F-Score {int(f_score.value)}/9 (weak group, "
                               "Piotroski 2000)")
    z = by_code.get("altman_z_score")
    if z is not None and z.ok:
        if z.value > Decimal("2.60"):
            result.pros.append(f"Altman Z'' {float(z.value):.2f} - safe zone")
        elif z.value < Decimal("1.10"):
            result.cons.append(f"Altman Z'' {float(z.value):.2f} - distress zone")
    m = by_code.get("beneish_m_score")
    if m is not None and m.ok and m.value > Decimal("-1.78"):
        result.cons.append(f"Beneish M-Score {float(m.value):.2f} above -1.78 (screening "
                           "signal for earnings manipulation; investigate)")
    payout = by_code.get("dividend_payout_ratio")
    if payout is not None and payout.ok and payout.value > 100:
        result.cons.append(f"Dividends paid exceed net income (payout "
                           f"{float(payout.value):.0f}%)")
    return result
